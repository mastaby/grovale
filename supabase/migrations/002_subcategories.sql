-- Run after schema.sql. Adds normalized subcategories and links products to them.
create table if not exists public.subcategories (
  id bigint generated by default as identity primary key,
  category_id bigint not null references public.categories(id) on delete cascade,
  name text not null,
  slug text not null,
  description text,
  created_at timestamptz not null default now(),
  unique(category_id, slug)
);

alter table public.products add column if not exists subcategory_id bigint references public.subcategories(id) on delete set null;
alter table public.subcategories enable row level security;
drop policy if exists "Public can view subcategories" on public.subcategories;
create policy "Public can view subcategories" on public.subcategories for select using (true);

insert into public.categories (name, slug) values
  ('Vegetables & Fruits','vegetables-fruits'), ('Atta, Rice & Dal','atta-rice-dal'),
  ('Oil, Ghee & Masala','oil-ghee-masala'), ('Dairy, Bread & Eggs','dairy-bread-eggs'),
  ('Bakery & Biscuits','bakery-biscuits'), ('Bath & Body','bath-body'), ('Hair','hair'),
  ('Skin & Face','skin-face'), ('Beauty & Cosmetics','beauty-cosmetics'), ('Feminine Hygiene','feminine-hygiene'),
  ('Baby Care','baby-care'), ('Health & Pharma','health-pharma'), ('Sexual Wellness','sexual-wellness'),
  ('Dry Fruits & Cereals','dry-fruits-cereals'), ('Chicken, Meat & Fish','chicken-meat-fish'),
  ('Kitchenware & Appliances','kitchenware-appliances'), ('Electronics','electronics'),
  ('Stationery & Games','stationery-games'), ('Hotel Essentials','hotel-essentials'), ('Restaurant Supplies','restaurant-supplies')
on conflict (slug) do update set name=excluded.name;

insert into public.subcategories (category_id, name, slug)
select c.id, v.name, v.slug from public.categories c cross join (values
  ('Fresh vegetables','fresh-vegetables'), ('Fresh fruits','fresh-fruits'),
  ('Leafy greens','leafy-greens'), ('Herbs','herbs')
) v(name,slug) where c.slug='vegetables-fruits'
on conflict (category_id, slug) do update set name=excluded.name;
