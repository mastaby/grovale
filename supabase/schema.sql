-- Pahalgam Delivery foundation schema
create extension if not exists pgcrypto;

create type public.order_type as enum ('individual', 'hotel_guest', 'hotel_essentials', 'restaurant_supplies');
create type public.order_status as enum ('pending', 'confirmed', 'preparing', 'out_for_delivery', 'delivered', 'cancelled');

create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text,
  phone text,
  email text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.addresses (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.profiles(id) on delete cascade,
  label text not null default 'Primary',
  address_line text not null,
  district text,
  city text,
  state text,
  hotel_name text,
  room_number text,
  delivery_instructions text,
  created_at timestamptz not null default now()
);

create table public.saved_delivery_profiles (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.profiles(id) on delete cascade,
  order_type public.order_type not null,
  customer_name text not null,
  phone text not null,
  delivery_address text,
  district text,
  city text,
  state text,
  hotel_name text,
  room_number text,
  business_name text,
  delivery_slot text,
  delivery_instructions text,
  updated_at timestamptz not null default now(),
  unique(user_id, order_type)
);

create table public.categories (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  slug text not null unique,
  description text,
  created_at timestamptz not null default now()
);

create table public.subcategories (
  id bigint generated by default as identity primary key,
  category_id bigint not null references public.categories(id) on delete cascade,
  name text not null,
  slug text not null,
  description text,
  created_at timestamptz not null default now(),
  unique(category_id, slug)
);

create table public.products (
  id uuid primary key default gen_random_uuid(),
  category_id uuid references public.categories(id) on delete set null,
  subcategory_id bigint references public.subcategories(id) on delete set null,
  name text not null,
  slug text not null unique,
  description text,
  price numeric(10,2) not null check (price >= 0),
  unit text,
  mrp numeric(10,2) check (mrp >= 0),
  discount_percentage numeric(5,2) check (discount_percentage >= 0 and discount_percentage <= 100),
  delivery_eta text,
  image_url text,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.carts (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null unique references public.profiles(id) on delete cascade,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.cart_items (
  id uuid primary key default gen_random_uuid(),
  cart_id uuid not null references public.carts(id) on delete cascade,
  product_id uuid not null references public.products(id) on delete cascade,
  quantity integer not null default 1 check (quantity > 0),
  unique(cart_id, product_id)
);

create table public.orders (
  id uuid primary key default gen_random_uuid(),
  user_id uuid references public.profiles(id) on delete set null,
  order_type public.order_type not null,
  status public.order_status not null default 'pending',
  customer_name text not null,
  phone text not null,
  delivery_address text,
  district text,
  city text,
  state text,
  hotel_name text,
  room_number text,
  business_name text,
  delivery_slot text,
  delivery_instructions text,
  subtotal numeric(10,2) not null default 0,
  delivery_fee numeric(10,2) not null default 0,
  total numeric(10,2) not null default 0,
  created_at timestamptz not null default now()
);

create table public.order_items (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null references public.orders(id) on delete cascade,
  product_id uuid references public.products(id) on delete set null,
  product_name text not null,
  unit_price numeric(10,2) not null,
  quantity integer not null check (quantity > 0),
  line_total numeric(10,2) not null
);

alter table public.profiles enable row level security;
alter table public.addresses enable row level security;
alter table public.saved_delivery_profiles enable row level security;
alter table public.carts enable row level security;
alter table public.cart_items enable row level security;
alter table public.orders enable row level security;
alter table public.order_items enable row level security;
alter table public.categories enable row level security;
alter table public.subcategories enable row level security;
alter table public.products enable row level security;

create policy "Public can view active products" on public.products for select using (active = true);
create policy "Public can view categories" on public.categories for select using (true);
create policy "Public can view subcategories" on public.subcategories for select using (true);
create policy "Users manage their profile" on public.profiles for all using (auth.uid() = id) with check (auth.uid() = id);
create policy "Users manage their addresses" on public.addresses for all using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "Users manage their saved delivery profiles" on public.saved_delivery_profiles for all using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "Users manage their cart" on public.carts for all using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "Users manage their cart items" on public.cart_items for all using (exists (select 1 from public.carts c where c.id = cart_id and c.user_id = auth.uid())) with check (exists (select 1 from public.carts c where c.id = cart_id and c.user_id = auth.uid()));
create policy "Users view their orders" on public.orders for select using (auth.uid() = user_id);
create policy "Users view their order items" on public.order_items for select using (exists (select 1 from public.orders o where o.id = order_id and o.user_id = auth.uid()));

create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  insert into public.profiles (id, full_name, email)
  values (new.id, new.raw_user_meta_data->>'full_name', new.email);
  return new;
end;
$$;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute procedure public.handle_new_user();

